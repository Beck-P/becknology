const BARS = { bar: 1, bar2: 2, bar3: 3 };
const GEM = { A: '#f078a8', K: '#5cc8d0', Q: '#a080f0', J: '#60e080' };

/** A symbol's 16 × 16 sprite. */
export function symbol(id) {
  if (S[id]) return sprite('sym:' + id, S[id].rows.map((r) => r.padEnd(16, '.').slice(0, 16)), S[id].p);
  if (BARS[id]) {
    return baked('sym:' + id, 16, 16, (g) => {
      const n = BARS[id], h = n === 1 ? 6 : n === 2 ? 10 : 14, y0 = Math.round((16 - h) / 2);
      for (let i = 0; i < n; i++) {
        const y = y0 + i * 4 + (n === 1 ? 0 : 0);
        const bh = n === 1 ? 6 : 3;
        g.fillStyle = k; g.fillRect(0, y - 1, 16, bh + 2);
        g.fillStyle = i % 2 ? '#e8e0f8' : '#ffffff'; g.fillRect(1, y, 14, bh);
        g.fillStyle = '#1c1830';
        if (n === 1) { g.fillRect(3, y + 1, 2, 4); g.fillRect(7, y + 1, 2, 4); g.fillRect(11, y + 1, 2, 4); }
        else { g.fillRect(3, y + 1, 10, 1); }
      }
    });
  }
  if (GEM[id]) {
    return baked('sym:' + id, 16, 16, (g) => {
      text(g, id, 3, 1, GEM[id], { scale: 2, outline: k });
      g.globalAlpha = 0.5; g.fillStyle = '#ffffff'; g.fillRect(3, 1, 10, 2); g.globalAlpha = 1;
      g.globalCompositeOperation = 'destination-in'; text(g, id, 3, 1, '#000', { scale: 2, outline: k }); g.globalCompositeOperation = 'source-over';
    });
  }
  return baked('sym:blank', 16, 16, (g) => { g.fillStyle = 'rgba(255,255,255,0.08)'; g.fillRect(6, 7, 4, 2); });
}
